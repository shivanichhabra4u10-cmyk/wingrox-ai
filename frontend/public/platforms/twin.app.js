function selectOpt(qIdx, optIdx) {
  const q = APP.questionsList[qIdx];
  if(!q||q.type==='divider') return;
  const wasAnswered = APP.answers[q.id] !== undefined;
  APP.answers[q.id] = optIdx;
  if(!wasAnswered) { answeredCount++; }
  // UI
  const grid = document.getElementById('opts-'+qIdx);
  grid.querySelectorAll('.q-opt').forEach((el,i)=>{
    el.classList.toggle('sel', i===optIdx);
  });
  // Auto advance after 400ms
  setTimeout(()=>nextQ(), 350);
}

function optKey(e, qIdx, optIdx) {
  if(e.key==='Enter'||e.key===' ') { e.preventDefault(); selectOpt(qIdx,optIdx); }
}

function nextQ() {
  const pkg = PACKAGES[APP.package || 'nucleus'];
  // Check package question limit
  const answered = Object.keys(APP.answers).length;
  const limit = pkg.qLimit;
  if(answered >= limit && APP.questionsList[currentQGlobal]?.type !== 'divider') {
    // Hit package limit — show dopamine and go to AI/report
    showDopamineHook('Must-Win', {...APP.answers}, () => {
      if(pkg.aiFollowup) startAILayer();
      else startProcessing();
    });
    return;
  }
  let next = currentQGlobal + 1;
  if(next >= APP.questionsList.length) {
    showDopamineHook('Must-Win', {...APP.answers}, () => {
      if(pkg.aiFollowup) startAILayer();
      else startProcessing();
    });
    return;
  }
  // Check for section transition (dopamine hook)
  const currentQ = APP.questionsList[currentQGlobal];
  const nextQ_ = APP.questionsList[next];
  if(currentQ?.type !== 'divider' && nextQ_?.type !== 'divider' && nextQ_?.section && currentQ?.section && nextQ_.section !== currentQ.section) {
    // Section boundary — navigate directly (dopamine hooks disabled)
    goToQIndex(next);
    return;
  }
  goToQIndex(next);
}

function prevQ() {
  if(currentQGlobal > 0) goToQIndex(currentQGlobal - 1);
}

function handleGlobalKey(e) {
  if(APP.page !== 'screening') return;
  const q = APP.questionsList[currentQGlobal];
  if(!q||q.type==='divider') {
    if(e.key==='Enter') nextQ();
    return;
  }
  const keys = ['a','b','c','d','f','g','h','i','j','k','l','m','n','p'];
  const ki = keys.indexOf(e.key.toLowerCase());
  if(ki >= 0 && ki < q.options.length) { selectOpt(currentQGlobal, ki); return; }
  const numKey = parseInt(e.key);
  if(!isNaN(numKey)&&numKey>=1&&numKey<=9&&numKey<=q.options.length) { selectOpt(currentQGlobal, numKey-1); return; }
  if(e.key==='ArrowRight'||e.key==='Enter') { if(!e.target.matches('textarea,input')) { e.preventDefault(); nextQ(); } }
  if(e.key==='ArrowLeft') { if(!e.target.matches('textarea,input')) { e.preventDefault(); prevQ(); } }
}

