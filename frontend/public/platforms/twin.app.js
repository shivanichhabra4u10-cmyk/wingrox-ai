// Track section transitions for dopamine hooks
let lastSection = null;
let sectionAnswerSnapshot = {};

function checkSectionTransition(idx) {
  const q = APP.questionsList[idx];
  if(!q || q.type === 'divider') return;
  const section = q.section;
  if(lastSection && section !== lastSection) {
    // Section changed — fire dopamine hook
    const next = idx;
    goToQIndex(next); // dopamine hooks disabled
    lastSection = section;
    return true; // signal: intercepted
  }
  lastSection = section;
  return false;
}

